a = 10 
b = 23
print(a == b)#if a both operand are equal then condition become true.
print(a != b)#if a both operand are  not equal then condition become true.
print(a > b)#if a left operand is greater than right operand then condition becomes true.
print(a < b)#if a left operand is lesser than right operand then condition becomes true.
print(a >= b)#if a left operand is greater than or equal right operand then condition becomes true.
print(a <= b)#if a left operand is lesser than or equal right operand then condition becomes true.